  function storedLocale() {
    try { return localStorage.getItem("radar-locale"); } catch (error) { return null; }
  }

  const requested = storedLocale() || (navigator.language || "en").split("-")[0];
  const locale = Object.hasOwn(messages, requested) ? requested : "en";

  function t(key, values = {}) {
    const template = messages[locale][key] ?? messages.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
  }

  document.documentElement.lang = locale;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    element.innerHTML = t(element.dataset.i18nHtml);
  });
  for (const [attribute, dataName] of [["aria-label", "i18nAriaLabel"], ["title", "i18nTitle"], ["placeholder", "i18nPlaceholder"], ["content", "i18nContent"]]) {
    document.querySelectorAll(`[data-${dataName.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`)}]`).forEach((element) => {
      element.setAttribute(attribute, t(element.dataset[dataName]));
    });
  }

  document.querySelectorAll("#guide-link, .guide-link").forEach((link) => {
    if (locale === "es") link.href = "https://github.com/TanbirRamim/open-source-radar/blob/main/guide/es/README.md";
    if (locale === "hi") link.href = "https://github.com/TanbirRamim/open-source-radar/blob/main/guide/hi/README.md";
  });

  const select = document.getElementById("locale-select");
  select.value = locale;
  select.addEventListener("change", () => {
    try { localStorage.setItem("radar-locale", select.value); } catch (error) { /* storage unavailable */ }
    location.reload();
  });

  window.RadarI18n = { locale, t, messages };
